/**
 * 假测试判据里可以独立验证的那一块：恒等断言识别。
 *
 * 单独成模块是为了让它能被 `node --test` 直接断言。门禁脚本的判据一旦没有回归测试，
 * 判据被改坏（放宽到抓不住、或误伤合法写法）不会有任何东西变红 ——
 * 而它恰恰是「谁来验验证者」的那条链。
 *
 * 只放**纯文本判定**：输入两个实参的源码文本，输出是不是恒等。不读文件、不扫目录。
 */
const squash = (s) => s.replace(/\s+/g, '')

/** 含函数调用的实参：会被求值两次，实现不确定时两边完全可以不等。 */
const hasCall = (s) => /[\w$)\]]\s*\(/.test(s)

/**
 * 两个实参是不是「永不失败的相等断言」。
 *
 * 三条边界都是踩出来的，改任何一条都会立刻产生误报或漏报：
 * - **归一化只抹空白**：抹字面量会把「结构相同、值不同」的两个实参判成恒等。
 *   比较还要用未遮罩的原文 —— 遮罩把字符串内容抹平后 `f('a')` 与 `f('b')` 会被判成一样。
 * - **含调用的实参不算恒等**：`assert.equal(fmt(r), fmt(r))` 是确定性测试，
 *   它要验的就是「两次求值一致」。把这类算成恒等，就是拿形状当语义，
 *   后果比漏报更贵 —— 它会驱动人去改一条本来就对的测试。
 * - **空串不算**：扫不到实参时不判，避免把「没解析出来」当成「解析出相等了」。
 *
 * @param {string} lhs 第一个实参的源码文本
 * @param {string} rhs 第二个实参的源码文本
 * @returns {boolean} 两边是否同一份纯表达式（归一化后逐字符相同且不含调用）
 */
export function isTautology(lhs, rhs) {
  const a = squash(lhs)
  if (a === '') return false
  if (a !== squash(rhs)) return false
  return !hasCall(lhs)
}
