/**
 * releaseId —— **只此一个来源**。
 *
 * 为什么要收成一个模块而不是各命令各写一份：releaseId 同时出现在三处 ——
 * 目标机上的目录名、`.dp/index.json`、CI 日志。三处算法只要有一处不同步，
 * 就会出现「日志说的版本和磁盘上建的目录对不上」这类查起来极其痛苦的偏差。
 * 更要紧的是 plan 的 preview 值必须与 apply 的真 id 同源，否则干跑里看到的
 * 目录名和真部署建的目录名不是一回事，plan 就失去了参考价值。
 *
 * 纯函数，无 IO —— 格式一旦定死就不能悄悄改，历史 release 的目录名依赖它。
 */

/**
 * UTC 时间戳：去掉 `-` `:` 与毫秒，`T` 换成 `-`。
 * `2026-10-02T09:30:00.123Z` → `20261002-093000`
 *
 * 必须用 UTC 而不是本地时间：跨时区执行同一份流水线时，本地时间会让同一个
 * 发布在两台机器上算出两个不同的目录名，索引和回滚全对不上。
 *
 * 毫秒被**丢弃**是刻意的：id 只需要人类可读且大致有序；留着毫秒只会让
 * 「同一次部署」的 id 在日志里长得几乎一样却不相等，反而看不出差别。
 */
function utcStamp(now: Date): string {
  return now.toISOString().replace(/[-:]/g, '').replace(/\..+/, '').replace('T', '-')
}

/**
 * 真部署用的 releaseId：`web-20261002-093000`。
 *
 * 同一 `now` 多次调用必然得到同一个值（纯函数，无隐藏状态）——`dp apply` 里
 * 反复用到它，值变了就会写进不同的目录。
 *
 * 关于项目名里的空格与斜杠：**原样保留，不做任何替换**。理由是铁律 2 ——
 * 歧义靠拒绝，不靠默认值。把 `a/b` 悄悄换成 `a_b` 会让「配置里写的」和
 * 「磁盘上建的」不再是同一个东西，而任何一种替换规则（换成 `_` 还是 `-`？）
 * 都是猜测，猜错等于静默部署到了别处。项目名来自 configSchema 校验过的配置，
 * 正常用法本来就不含分隔符；真出现了路径逃逸风险，那属于校验层该拦的，
 * 不该由格式化函数替它做决定。
 */
export function releaseIdFor(name: string, now: Date): string {
  return `${name}-${utcStamp(now)}`
}

/**
 * 只读命令用的预览 id：`preview-web-20261002-093000`。
 *
 * `preview-` 前缀是**语义标记**而不是装饰：它在文件系统上不可能与任何真
 * releaseId 撞名，所以 plan 打印出来的目录名绝对安全，同时又让人一眼看出
 * 「这是算出来的，还没有真的建」。
 */
export function previewReleaseId(name: string, now: Date): string {
  return `preview-${releaseIdFor(name, now)}`
}
